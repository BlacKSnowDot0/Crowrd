async def enrich_batch(session: aiohttp.ClientSession, sem: asyncio.Semaphore, batch: list, batch_idx: int, total_batches: int):
    brief_list = []
    for s in batch:
        seeds = s["_seeds"]
        is_tehran = s["city"] == "تهران"
        loc_rule = "ساکن تهران است (پس «ارسال رایگان شهرستان» ننویس!)" if is_tehran else f"ساکن {s['city']} ({s['province']}) است (مسیر رفت‌وآمد فقط درون همان شهر یا شهرهای نزدیک همان استان باشد!)"
        marital_rule = "مجرد است (اصلاً از همسر یا فرزند حرف نزن!)" if s["marital_status"] == "مجرد" else s["marital_status"]
        housing_rule = "مالک خانه است (اجاره مسکن نمی‌پردازد!)" if s["housing"] == "مالک" else s["housing"]

        brief_list.append({
            "id": s["id"],
            "name": s["name"],
            "profile": f"{s['gender']} {s['age']} ساله، محله {s['neighborhood']} در {s['city']} ({s['province']}، {s['regional_flavor']})، شغل: {s['job']}، درآمد ۱۴۰۵: {s['monthly_income_m']} میلیون تومان ({s['income_tier']})، وضعیت تاهل: {marital_rule}، مسکن: {housing_rule}، اپ‌ها: {'، '.join(s['platforms'])}، تیپ تبلیغی: {s['ad_archetype']} (بدبینی {s['ad_skepticism']} از ۵). {loc_rule}",
            "angle": seeds["opening_style"],
            "money_reality": seeds["fin_seed"],
            "digital_habit": seeds["dig_seed"],
            "shopping_story_seed": seeds["exp_seed"],
        })

    prompt = f"""تو پژوهشگر ارشد جامعه‌شناسی و رفتار مصرف‌کننده در ایران سال ۱۴۰۵ هستی.
برای هر کدام از {len(batch)} شخص زیر، یک پروفایل **فوق‌العاده واقعی، ملموس، زنده و کاملاً متفاوت از بقیه** به فارسی طبیعی سال ۱۴۰۵ بنویس.

قوانین طلایی ضدکلیشه و واقع‌گرایی (اجباری!):
1) **ممنوعیت مطلق کلیشه‌های تکراری**:
   - از عبارات تکراری مثل «از آن روز»، «از آن موقع»، «از آن به بعد»، «از اون موقع»، «یک بار از یک پیج اینستاگرامی»، «ساعت مچی تقلبی»، «پکیج درآمد اینترنتی»، «پشتیبانی گوشی را قطع کرد» **اصلاً استفاده نکن!**
   - هر شخص باید با `angle` (زاویه شروع) اختصاصی خودش شروع شود تا جملات اول هیچ دو نفری شبیه هم نباشد!
2) **واقعیت زنده ۱۴۰۵ ایران**:
   - `money_reality`، `digital_habit` و `shopping_story_seed` را طبیعی در دل داستان بباف (کپی خشک نکن، مثل آدم واقعی روایت کن).
   - اعداد تومانی واقعی، اسم محله و شهر خودش و پلتفرم‌های واقعی خودش (دیجی‌کالا، ترب، باسلام، اسنپ‌پی، دیجی‌پی، تارا، بلوبانک، ویپاد، طلاین، میلی، ایتا، روبیکا، بله، دیوار، فیلترشکن و...) را به‌جا بیاور.
   - اگر `بدبینی` ۱ یا ۲ است، فرد واقعاً گشوده، کنجکاو یا اهل امتحان کردن است (الکی بدبین و غرغرو ننویس!). اگر ۴ یا ۵ است، دلیل ملموس و منطقی برای احتیاطش بیاور.
3) **انسجام صددرصدی**:
   - تناقض ممنوع! مجرد از همسر/بچه نگوید، مالک از اجاره خانه نگوید، تهرانی نگوید «ارسال به شهرستان»، مسافت جغرافیایی عجیب نساز.
4) **طول دقیق و دقیقاً ۴ فیلد خروجی برای هر نفر**:
   - `life_story`: **دقیقاً بین ۱۱۵ تا ۱۵۰ کلمه فارسی** (نه کوتاه‌تر از ۱۰۵ و نه طولانی‌تر از ۱۶۰). پر از جزئیات ملموس زندگی روزمره، دغدغه مالی/زمانی، رفتار واقعی هنگام دیدن تبلیغ و معیار توقف یا رد کردن.
   - `voice_sample`: یک جمله کوتاه و بسیار طبیعی و محاوره‌ای (۱۰ تا ۲۰ کلمه) که دقیقاً با لحن سن، شغل و شهر این شخص موقع دیدن یک تبلیغ جور باشد (شروع‌های متنوع!).
   - `triggers`: آرایه دقیقاً ۳ تگ کوتاه و اختصاصی (۲ تا ۴ کلمه) متناسب با همین شخص — نه کپی تکراری!
   - `red_flags`: آرایه دقیقاً ۳ تگ کوتاه و اختصاصی (۲ تا ۴ کلمه) متناسب با خطوط قرمز همین شخص!

ورودی اشخاص:
{json.dumps(brief_list, ensure_ascii=False)}

خروجی را دقیقاً به صورت JSON با کلید `profiles` برگردان:
{{"profiles": [{{"id": "...", "life_story": "...", "voice_sample": "...", "triggers": ["...", "...", "..."], "red_flags": ["...", "...", "..."]}}]}}"""

    async with sem:
        for attempt in range(4):
            t0 = time.perf_counter()
            try:
                async with session.post(
                    "https://api.deepseek.com/chat/completions",
                    headers={"Authorization": f"Bearer {DEEPSEEK_KEY}", "Content-Type": "application/json"},
                    json={
                        "model": "deepseek-flash",
                        "messages": [{"role": "user", "content": prompt}],
                        "max_tokens": 5200,
                        "temperature": 0.92,
                        "thinking": {"type": "disabled"},
                        "response_format": {"type": "json_object"},
                    },
                    timeout=aiohttp.ClientTimeout(total=120),
                ) as resp:
                    text = await resp.text()
                    if resp.status == 429:
                        await asyncio.sleep(3 * (attempt + 1))
                        continue
                    if resp.status != 200:
                        raise RuntimeError(f"HTTP {resp.status}: {text[:300]}")
                    data = json.loads(text)
                    content = data["choices"][0]["message"]["content"]
                    parsed = json.loads(content)
                    items = {}
                    for p in parsed.get("profiles", []):
                        pid = p.get("id")
                        ls = str(p.get("life_story") or "").strip()
                        vs = str(p.get("voice_sample") or "").strip()
                        tr = p.get("triggers")
                        rf = p.get("red_flags")
                        if pid and len(ls.split()) >= 50 and vs and isinstance(tr, list) and len(tr) >= 2 and isinstance(rf, list) and len(rf) >= 2:
                            items[pid] = p
                    if len(items) < len(batch):
                        raise ValueError(f"Only {len(items)}/{len(batch)} complete profiles with all 4 fields")
                    ms = round((time.perf_counter() - t0) * 1000)
                    usage = data.get("usage", {})
                    if (batch_idx + 1) % 10 == 0 or batch_idx == 0 or batch_idx + 1 == total_batches:
                        print(f"  Batch {batch_idx+1:03d}/{total_batches} OK ({len(items)} profiles, {ms}ms, {usage.get('completion_tokens', 0)} out_tok)", flush=True)
                    return items, usage
            except Exception as e:
                print(f"  Batch {batch_idx+1:03d}/{total_batches} attempt {attempt+1} error: {e}", flush=True)
                await asyncio.sleep(2.5 * (attempt + 1))
        raise RuntimeError(f"Batch {batch_idx+1} failed after 4 retries")


async def main():
    n_total = 1000
    batch_size = 8
    total_batches = (n_total + batch_size - 1) // batch_size

    print(f"Building {n_total} 1405-grounded Iranian skeletons across all 31 provinces...", flush=True)
    t0 = time.perf_counter()
    skeletons = build_skeletons(n_total)

    # Quick sanity print of skeleton distributions
    print(f"  Provinces: {len(set(s['province'] for s in skeletons))} | Cities: {len(set(s['city'] for s in skeletons))} | Hoods: {len(set(s['neighborhood'] for s in skeletons))} | Unique names: {len(set(s['name'] for s in skeletons))}", flush=True)
    print(f"  Gender: {dict(Counter(s['gender'] for s in skeletons))}", flush=True)
    print(f"  City tiers: {dict(Counter(s['city_tier'] for s in skeletons))}", flush=True)
    print(f"  Income tiers: {dict(Counter(s['income_tier'] for s in skeletons))}", flush=True)
    print(f"  Skepticism: {dict(sorted(Counter(s['ad_skepticism'] for s in skeletons).items()))}", flush=True)

    print(f"\nEnriching {n_total} profiles in {total_batches} batches (batch_size={batch_size}, concurrency=15) via deepseek-flash...", flush=True)
    sem = asyncio.Semaphore(15)
    total_in = 0
    total_out = 0
    enriched_map = {}

    connector = aiohttp.TCPConnector(limit=20)
    async with aiohttp.ClientSession(connector=connector) as session:
        tasks = [
            enrich_batch(session, sem, skeletons[i : i + batch_size], i // batch_size, total_batches)
            for i in range(0, n_total, batch_size)
        ]
        results = await asyncio.gather(*tasks)
        for items, usage in results:
            enriched_map.update(items)
            total_in += usage.get("prompt_tokens", 0)
            total_out += usage.get("completion_tokens", 0)

    final_profiles = []
    for s in skeletons:
        e = enriched_map[s["id"]]
        clean_s = {k: v for k, v in s.items() if not k.startswith("_")}
        triggers = [str(t).strip() for t in (e.get("triggers") or []) if str(t).strip()][:3]
        red_flags = [str(r).strip() for r in (e.get("red_flags") or []) if str(r).strip()][:3]
        final_profiles.append({
            **clean_s,
            "life_story": re.sub(r"\s+", " ", str(e["life_story"])).strip(),
            "voice_sample": re.sub(r"\s+", " ", str(e["voice_sample"])).strip().strip("«»\"'"),
            "triggers": triggers,
            "red_flags": red_flags,
        })

    payload = {
        "version": "2.0-raw",
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "count": len(final_profiles),
        "profiles": final_profiles,
    }
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)

    elapsed = time.perf_counter() - t0
    cost = total_in * 0.15 / 1e6 + total_out * 0.60 / 1e6
    avg_words = sum(len(p["life_story"].split()) for p in final_profiles) / len(final_profiles)

    stats = {
        "stage": "raw_1000",
        "count": len(final_profiles),
        "elapsed_sec": round(elapsed, 1),
        "input_tokens": total_in,
        "output_tokens": total_out,
        "cost_usd": round(cost, 4),
        "avg_bio_words": round(avg_words, 1),
    }
    with open(META_FILE, "w", encoding="utf-8") as f:
        json.dump(stats, f, ensure_ascii=False, indent=2)

    print(f"\nDONE! {len(final_profiles)} raw profiles saved to {OUT_FILE}", flush=True)
    print(f"  Time: {elapsed:.1f}s | Avg words: {avg_words:.1f} | Tokens: {total_in:,} in / {total_out:,} out | Est cost: ${cost:.4f}", flush=True)
    for idx in [0, 123, 456, 888]:
        p = final_profiles[idx]
        print(f"  [{p['id']}] {p['name']} ({p['age']}yo {p['gender']}, {p['neighborhood']} {p['city']}, {p['job']}, {p['monthly_income_m']}M, skep={p['ad_skepticism']}):")
        print(f"    Bio ({len(p['life_story'].split())}w): {p['life_story'][:200]}...")
        print(f"    Voice: «{p['voice_sample']}»")


