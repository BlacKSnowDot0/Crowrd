def pick_authentic_name(rng: random.Random, gender: str, age: int, culture: str, used: set) -> str:
    pool_map = NAMES_F if gender == "زن" else NAMES_M
    gen_key = "persian_young" if age <= 30 else ("persian_mid" if age <= 48 else "persian_older")

    for _ in range(120):
        # 55% regional cultural first name for non-persian regions (more natural mix!)
        if culture != "persian" and rng.random() < 0.55:
            fn = rng.choice(pool_map[culture])
        else:
            fn = rng.choice(pool_map[gen_key])

        if culture != "persian" and rng.random() < 0.60:
            ln = rng.choice(SURNAMES[culture])
        else:
            ln = rng.choice(SURNAMES["persian"])

        full = f"{fn} {ln}"
        if full not in used:
            used.add(full)
            return full
    raise RuntimeError("Exhausted unique name space!")


def pick_neighborhood(rng: random.Random, hoods: dict, income_m: int, housing: str, age: int, city_tier: str) -> str:
    """Strictly correlates neighborhood socioeconomic tier with income & housing so no 25M renter lives in Elahieh!"""
    if housing == "مستاجر":
        if city_tier == "تهران":
            if income_m >= 120:
                band = rng.choices(["high", "mid"], weights=[0.55, 0.45])[0]
            elif income_m >= 55:
                band = rng.choices(["mid", "budget"], weights=[0.70, 0.30])[0]
            else:
                band = rng.choices(["budget", "mid"], weights=[0.85, 0.15])[0]
        else:
            if income_m >= 95:
                band = rng.choices(["high", "mid"], weights=[0.60, 0.40])[0]
            elif income_m >= 42:
                band = rng.choices(["mid", "budget"], weights=[0.72, 0.28])[0]
            else:
                band = rng.choices(["budget", "mid"], weights=[0.82, 0.18])[0]
    elif housing == "مالک":
        if income_m >= 105:
            band = rng.choices(["high", "mid"], weights=[0.68, 0.32])[0]
        elif income_m >= 48:
            band = rng.choices(["mid", "high", "budget"], weights=[0.62, 0.18, 0.20])[0]
        elif age >= 54:
            # Older owners may still own a house in mid/high bought decades ago!
            band = rng.choices(["mid", "budget", "high"], weights=[0.55, 0.35, 0.10])[0]
        else:
            band = rng.choices(["budget", "mid"], weights=[0.65, 0.35])[0]
    else:  # با خانواده
        if income_m >= 75:
            band = rng.choices(["high", "mid"], weights=[0.45, 0.55])[0]
        elif income_m >= 32:
            band = rng.choices(["mid", "budget", "high"], weights=[0.60, 0.28, 0.12])[0]
        else:
            band = rng.choices(["mid", "budget"], weights=[0.50, 0.50])[0]

    return rng.choice(hoods[band])


